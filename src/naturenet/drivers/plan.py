"""
Plan the environmental-driver study of one species as a sit_fuse.local_launcher plan.

Reads config/v2/drivers/<species>_drivers.yaml and writes, into its generated_dir (package-relative):
  year/<level>_<run>.yaml        test 3 run configs: year folds (n_folds = number of year groups, folds_dir of
                                 year_transfer), run_uid + "_YEAR", out_dir + "_year/", K fixed, reduced scales grid
  envswitch/<level>_<run>.yaml   test 7 scales configs: same run_uid / out_dir as the level's scales run (N1 shared),
                                 variants = env_switch.variants with switch_history kind "env" (env_channels, env_tag)
  coupling/<name>.yaml           test 6 multi-agent config: multiagent.null_kind env_matched (same ma_subdir; the
                                 observed parts / cache are shared with the time-shift run)
  specs/<analysis>.yaml          analysis specs: env_scale_grid, env_scale_grid_year, ppc, driver_consistency,
                                 coupling_env, switch_env, geometry, synthesis
and the plan (--out) with job groups

  fits      hiavi / scales K-fold per level and null (plan_jobs.hiavi_jobs / scales_jobs), year fits (after the
            year folds job), env-switch scales, env-matched multi-agent (obs / null chunks / merge)
  geometry  availability -> sample_env_inputs (available points) -> env_geometry parts; projection per level
  analysis  env_scale_grid (+ year), ppc per model x fold -> collect, driver_consistency per perspective ->
            collect, coupling_env, switch_env per model, correlation (test 7 series), synthesis (last)

The level configs must exist and be synced first (run_env_drivers.sh STAGE=setup). Every runner skips finished
work and the launcher keeps done markers, so plan + run can be repeated at any time.

    python -m naturenet.drivers.plan -y config/v2/drivers/whales_drivers.yaml --out /data/.../plan_drivers_whales.yaml \
        [--only fits,geometry,analysis] [--gpus 4,5] [--cpus 24]
"""
import argparse
import copy
import os
import shlex
import sys
from types import SimpleNamespace

import yaml

from naturenet.drivers.common import abs_cfg, pkg_dir, read_yaml, write_yaml

GROUPS = ("fits", "geometry", "analysis")
HDR = "# generated by naturenet.drivers.plan from {src}; do not edit (edit the drivers YAML and re-plan)\n"


# ----------------------------------------------------------------------------- paths
class Study:
    def __init__(self, path):
        self.path = abs_cfg(path)
        self.d = read_yaml(self.path)
        self.sp = self.d["species"]
        self.lspec = read_yaml(abs_cfg(self.d["levels_spec"]))
        self.gen = abs_cfg(self.d["generated_dir"])
        self.out = self.d["drivers_dir"]
        self.K = int(self.d.get("K", 5))

    def all_levels(self):
        return list(self.d["levels"]) + list(self.d.get("nulls") or [])

    def run_yaml(self, lv, run):
        if lv == "fine":
            return abs_cfg(self.d["fine"][run])
        return abs_cfg(os.path.join(self.d["level_config_dir"], lv, run + ".yaml"))

    def level_dir(self, lv):
        if lv == "fine":
            return self.lspec["base_dir"]
        return os.path.join(self.lspec["levels_dir"], lv, "")

    def gpath(self, *p):
        return os.path.join(self.gen, *p)

    def odir(self, name):
        return os.path.join(self.out, name, "")


def _write(conf, path, src):
    write_yaml(conf, path, header=HDR.format(src=os.path.relpath(src, pkg_dir())))
    return path


def _check_synced(path):
    c = read_yaml(path)
    if c.get("n_states") in (None, "null"):
        raise SystemExit(f"{path}: n_states is null - run the setup stage (make_level_configs, env_null, sync) first")
    return c


# ----------------------------------------------------------------------------- generated run configs
def year_configs(st):
    yt = st.d.get("year_transfer") or {}
    if not yt:
        return []
    n = len(str(yt["year_groups"]).split(";"))
    out = []
    for lv in yt.get("levels", ["fine"]):
        for run in yt.get("runs", []):
            src = st.run_yaml(lv, run)
            c = copy.deepcopy(_check_synced(src))
            c.update(n_folds=n, folds_dir=yt["folds_dir"], folds_to_run=None, run_uid=c["run_uid"] + "_YEAR",
                     out_dir=c["out_dir"].rstrip("/") + "_year/")
            if "min_latent" in c:
                c.update(min_latent=st.K, max_latent=st.K, n_hidden=st.K)
            c["run_hiavi_final"] = False
            if "scales" in c and yt.get("scales_grid"):
                s = c["scales"]
                s["grid"] = dict(yt["scales_grid"])
                s["variants"] = list(yt.get("scales_variants") or [])
            out.append((lv, run, _write(c, st.gpath("year", f"{lv}_{run}.yaml"), src)))
    return out


def envswitch_configs(st):
    es = st.d.get("env_switch") or {}
    out = []
    for lv in es.get("levels", ["fine"]):
        src = st.run_yaml(lv, es.get("run", "hiql_scales_kin_k5"))
        c = copy.deepcopy(_check_synced(src))
        s = c["scales"]
        s["grid"] = {"order": [1]}
        vs = []
        for v in es.get("variants") or []:
            v = copy.deepcopy(v)
            sh = dict(v.get("switch_history") or {})
            sh.setdefault("env_channels", list(es.get("channels") or []))
            sh.setdefault("env_tag", es.get("env_tag", "env"))
            v["switch_history"] = sh
            vs.append(v)
        s["variants"] = vs
        out.append((lv, _write(c, st.gpath("envswitch", f"{lv}_scales.yaml"), src)))
    return out


def coupling_config(st):
    cp = st.d.get("coupling") or {}
    if not cp:
        return None
    src = abs_cfg(cp["yaml"])
    c = copy.deepcopy(read_yaml(src))
    c.setdefault("multiagent", {})["null_kind"] = "env_matched"
    return _write(c, st.gpath("coupling", os.path.splitext(os.path.basename(src))[0] + "_envnull.yaml"), src)


# ----------------------------------------------------------------------------- analysis specs
def write_specs(st, year_cfgs):
    sp, K, specs = st.sp, st.K, {}
    el = st.d.get("env_levels") or {}
    runs = el.get("runs", ["hiavi_kfold_kin", "hiql_scales_kin_k5"])

    def grid_entries(pairs):
        e = []
        for lv, run, y in pairs:
            e.append(dict(level=lv, kind="hiavi" if "hiavi" in run else "scales", yaml=y, K=K, sweep=True))
        return e

    pairs = [(lv, r, st.run_yaml(lv, r)) for lv in st.all_levels() for r in runs]
    ref = el.get("reference") or {"level": "fine", "decision": "N1"}
    nulls = list(st.d.get("nulls") or [])
    specs["env_scale_grid"] = dict(out_dir=st.odir("env_scale_grid"), reference=ref, nulls=nulls, per_animal=True,
                                   title=f"{sp}: environment level x decision scale (paired held-out LL)",
                                   entries=grid_entries(pairs))
    if year_cfgs:
        specs["env_scale_grid_year"] = dict(out_dir=st.odir("env_scale_grid_year"), reference=ref,
                                            nulls=[n for n in nulls if any(lv == n for lv, _, _ in year_cfgs)],
                                            per_animal=True, entries=grid_entries(year_cfgs),
                                            title=f"{sp}: leave-year-out transfer (paired held-out LL)")
    pp = st.d.get("ppc") or {}
    models = [dict(label=m["label"], level=m.get("level", "fine"), yaml=st.run_yaml(m.get("level", "fine"), "hiavi_kfold_kin"), K=int(m.get("K", K)),
                   sweep=True) for m in pp.get("models") or []]
    specs["ppc"] = dict(out_dir=st.odir("ppc"), n_sim=int(pp.get("n_sim", 50)), seed=0, folds=None, models=models)
    cs = st.d.get("consistency") or {}
    persp = []
    for lv in cs.get("levels") or []:
        persp.append(dict(label=f"{lv}_hiql_kin", level=lv, kind="hiavi", yaml=st.run_yaml(lv, "hiavi_kfold_kin"), K=K,
                          projection=st.run_yaml(lv, "reward_env_projection_hiql"), folds="all"))
    for v in cs.get("scales_variants") or []:
        persp.append(dict(label=f"fine_scales_{v}", level="fine", kind="scales",
                          yaml=st.run_yaml("fine", "hiql_scales_kin_k5"), variant=f"HIQL_{v}",
                          projection=st.run_yaml("fine", "reward_env_projection_hiql")))
    if cs.get("multiagent"):
        m = cs["multiagent"]
        persp.append(dict(label=f"fine_ma_{m.get('fit', 'indep')}", level="fine", kind="multiagent",
                          yaml=abs_cfg(m["yaml"]), K=int(m.get("K", K)), fit=m.get("fit", "indep"),
                          projection=st.run_yaml("fine", "reward_env_projection_hiql")))
    specs["driver_consistency"] = dict(out_dir=st.odir("driver_consistency"), n_boot=int(cs.get("n_boot", 200)),
                                       variables=None, reference=persp[0]["label"] if persp else None,
                                       perspectives=persp)
    cp = st.d.get("coupling") or {}
    if cp:
        specs["coupling_env"] = dict(out_dir=st.odir("coupling_env"), runs=[dict(
            label=f"{sp}_ma_kin", yaml=abs_cfg(cp["yaml"]), projection=st.run_yaml("fine", "reward_env_projection_hiql"))])
    es = st.d.get("env_switch") or {}
    specs["switch_env"] = dict(out_dir=st.odir("switch_env"), channels=es.get("channels"), window=int(es.get("window", 3)),
                               n_perm=int(es.get("n_perm", 500)),
                               models=[m for m in models if not any(n in m["label"] for n in nulls)])
    g = dict(st.d.get("geometry") or {})
    if g:
        g = dict(out_dir=st.odir("geometry"), sample_inputs_yaml=abs_cfg(g["sample_inputs_yaml"]),
                 channels=g.get("channels"), env_transforms=g.get("env_transforms") or {},
                 availability=dict(sample_inputs_yaml=abs_cfg(g["sample_inputs_yaml"]), avl_dir=st.odir("availability"),
                                   n_available=int(g.get("n_available", 10)), seed=0),
                 levels={lv: st.level_dir(lv) for lv in st.d["levels"]}, group_regex=g.get("group_regex") or {},
                 k=int(g.get("k", 20)), max_points=int(g.get("max_points", 20000)), n_perm=int(g.get("n_perm", 199)),
                 projections=g.get("projections", ["native", "pca", "umap", "tsne"]), projection_n=3000, n_runs=3)
        specs["geometry"] = g
    specs["synthesis"] = dict(
        out_dir=st.odir("synthesis"), species=sp, reference=ref, no_env_level=el.get("no_env_level", "null_single"),
        inputs=dict(grid=st.odir("env_scale_grid"), grid_year=st.odir("env_scale_grid_year") if year_cfgs else None,
                    ppc=st.odir("ppc"), consistency=st.odir("driver_consistency"),
                    coupling=st.odir("coupling_env") if cp else None, switch=st.odir("switch_env"),
                    geometry=st.odir("geometry") if g else None),
        rank_sets=dict(
            levels=dict(item="level", exclude_items=nulls,
                        perspectives=["grid:test_ll@N1", "grid_year:test_ll@N1", "geometry:eta2_mean",
                                      "geometry:silhouette", "projection:native", "projection:pca"]),
            models=dict(item="model", perspectives=["ppc:log_score", "ppc:ece", "ppc:occupancy_js", "ppc:pit_ks"])))
    paths = {}
    for name, s in specs.items():
        paths[name] = _write(s, st.gpath("specs", f"{name}.yaml"), st.path)
    return paths


# ----------------------------------------------------------------------------- jobs
def _args(st, a):
    L = st.d.get("launcher") or {}
    return SimpleNamespace(gpu_share=float(L.get("gpu_share", 0.25)), hiavi_cpus=int(L.get("hiavi_cpus", 4)),
                           swirl_cpus=int(L.get("swirl_cpus", 2)), ma_cpus=int(L.get("ma_cpus", 4)),
                           null_chunk=int(L.get("null_chunk", 2)), arhmm_cpus=1, no_arhmm=True, ma_backend=None,
                           cpus=a.cpus, gpus=a.gpus)


def _cpu_env(n):
    return {"NATURENET_JAX_PLATFORM": "cpu", "JAX_PLATFORMS": "cpu", "OMP_NUM_THREADS": str(n)}


def _job(name, cmd, cpus=1, cases=None, after=None, needs=None, provides=None, id_keys=None, env=None):
    j = dict(name=name, cmd=cmd, cpus=int(cpus), gpu=0, env=env or _cpu_env(cpus))
    for k, v in (("cases", cases), ("after", after), ("needs", needs), ("provides", provides), ("id_keys", id_keys)):
        if v:
            j[k] = v
    return j


def _all(names, have):
    return [dict(name=n, on=[]) for n in names if n in have]


def build(st, a, only=GROUPS):
    from naturenet.models.irl import plan_jobs as pj
    ns = _args(st, a)
    q = shlex.quote
    py = "{py} -m naturenet.drivers."
    ac = int((st.d.get("launcher") or {}).get("analysis_cpus", 2))
    year_cfgs = year_configs(st)
    sw = envswitch_configs(st)
    cpl = coupling_config(st)
    specs = write_specs(st, year_cfgs)
    jobs, fit_groups, year_groups, ma_groups = [], {}, [], []

    el = st.d.get("env_levels") or {}
    if "fits" in only:
        for lv in st.all_levels():
            if lv == "fine" and not st.d.get("include_fine_fits", False):
                continue
            for run in el.get("runs", []):
                y = st.run_yaml(lv, run)
                _check_synced(y)
                g = pj.hiavi_jobs(y, ns) if "hiavi" in run else pj.scales_jobs(y, ns)
                fit_groups.setdefault(lv, []).extend(x["name"] for x in g)
                jobs += g
        yt = st.d.get("year_transfer") or {}
        if year_cfgs:
            n = len(str(yt["year_groups"]).split(";"))
            fseed = int(read_yaml(year_cfgs[0][2]).get("fold_seed", 0))
            fjson = os.path.join(yt["folds_dir"], f"folds_{n}_seed{fseed}.json")
            jobs.append(_job("year_folds", f"{py}year_folds -y {q(st.run_yaml('fine', 'hiavi_kfold_kin'))} "
                                           f"--folds_dir {q(yt['folds_dir'])} --year_groups {q(str(yt['year_groups']))}",
                             provides=[fjson]))
            for lv, run, y in year_cfgs:
                g = pj.hiavi_jobs(y, ns) if "hiavi" in run else pj.scales_jobs(y, ns)
                for x in g:
                    x["needs"] = list(x.get("needs") or []) + [fjson]
                year_groups += [x["name"] for x in g]
                jobs += g
        for lv, y in sw:
            g = pj.scales_jobs(y, ns)
            for x in g:            # N1 of this run_uid is shared with the level's scales grid
                x["after"] = _all(fit_groups.get(lv, []), {j["name"] for j in jobs})
            fit_groups.setdefault(lv, []).extend(x["name"] for x in g)
            jobs += g
        if cpl:
            cp = st.d["coupling"]
            spec = f"{cpl}@backend={cp.get('backend', 'hiavi')}" + (
                "@K=" + ",".join(str(k) for k in cp["K"]) if cp.get("K") else "")
            g = pj.multiagent_jobs(spec, ns)
            ma_groups = [x["name"] for x in g if x["name"].startswith("ma_merge")]
            jobs += g

    have = {j["name"] for j in jobs}
    geo = specs.get("geometry")
    if "geometry" in only and geo:
        gs = read_yaml(geo)
        avl = gs["availability"]["avl_dir"]
        uid = read_yaml(gs["sample_inputs_yaml"])["df_run_uid"]
        avl_dfs = os.path.join(avl, uid + "_dfs.pkl")
        avl_ch = os.path.join(avl, uid + "_states_input_channels.json")
        jobs.append(_job("availability", f"{py}availability -y {q(geo)}", provides=[avl_dfs]))
        jobs.append(_job("sample_avl", f"{{py}} -m naturenet.environment.sample_env_inputs -y "
                                       f"{q(os.path.join(avl, 'sample_inputs_avl.yaml'))}", cpus=4,
                         needs=[avl_dfs], provides=[avl_ch]))
        # lid / geo_env / levels use the used fixes only; id / selection also need the available points
        jobs.append(_job("geometry", f"{py}env_geometry -y {q(geo)} --part {{part}}", cpus=ac,
                         cases=[dict(part=p) for p in ("lid", "geo_env", "levels")]))
        jobs.append(_job("geometry_avl", f"{py}env_geometry -y {q(geo)} --part {{part}}", cpus=ac,
                         cases=[dict(part=p) for p in ("id", "selection")], needs=[avl_ch]))
        jobs.append(_job("projection", f"{py}projection_robustness -y {q(geo)} --level {{level}}", cpus=ac,
                         cases=[dict(level=lv) for lv in gs["levels"]]))
    have = {j["name"] for j in jobs}

    if "analysis" in only:
        all_fits = [n for v in fit_groups.values() for n in v]
        jobs.append(_job("grid", f"{py}env_scale_grid -y {q(specs['env_scale_grid'])}", cpus=ac,
                         after=_all(all_fits, have)))
        if "env_scale_grid_year" in specs:
            jobs.append(_job("grid_year", f"{py}env_scale_grid -y {q(specs['env_scale_grid_year'])}", cpus=ac,
                             after=_all(year_groups, have)))
        pp = read_yaml(specs["ppc"])
        nf = int(read_yaml(st.run_yaml("fine", "hiavi_kfold_kin")).get("n_folds", 5))
        lv_of = {m["label"]: m.get("level", "fine") for m in (st.d.get("ppc") or {}).get("models") or []}
        for m in pp["models"]:
            jobs.append(_job(f"ppc.{m['label']}", f"{py}ppc -y {q(specs['ppc'])} --model {m['label']} --fold {{fold}}",
                             cpus=ac, cases=[dict(fold=k) for k in range(nf)],
                             after=_all([n for n in fit_groups.get(lv_of[m["label"]], []) if n.startswith("hiavi.")],
                                        have)))
        ppc_names = [f"ppc.{m['label']}" for m in pp["models"]]
        jobs.append(_job("ppc_collect", f"{py}ppc -y {q(specs['ppc'])} --collect", after=_all(ppc_names,
                                                                                               {*have, *ppc_names})))
        cs = read_yaml(specs["driver_consistency"])
        cons_names = []
        for p in cs["perspectives"]:          # one job per perspective, waiting only for its own level's fits
            lv_fits = fit_groups.get(p.get("level", "fine"), [])
            pre = {"hiavi": "hiavi.", "scales": "scales."}.get(p.get("kind"))   # multi-agent: external fits
            nm = f"consistency.{p['label']}"
            cons_names.append(nm)
            dep = [n for n in lv_fits if pre and n.startswith(pre) and "envswitch-" not in n]
            jobs.append(_job(nm, f"{py}driver_consistency -y {q(specs['driver_consistency'])} "
                                 f"--perspective {q(p['label'])}", cpus=ac, after=_all(dep, have)))
        jobs.append(_job("consistency_collect", f"{py}driver_consistency -y {q(specs['driver_consistency'])} --collect",
                         after=_all(cons_names, set(cons_names))))
        if "coupling_env" in specs:
            jobs.append(_job("coupling_env", f"{py}coupling_env -y {q(specs['coupling_env'])}",
                             after=_all(ma_groups, have)))
        sw_spec = read_yaml(specs["switch_env"])
        for m in sw_spec["models"]:
            lv_fits = [n for n in fit_groups.get(m.get("level", "fine"), []) if n.startswith("hiavi.")]
            jobs.append(_job(f"switch.{m['label']}", f"{py}switch_env -y {q(specs['switch_env'])} --model {m['label']}",
                             cpus=ac, after=_all(lv_fits, have)))
        es = st.d.get("env_switch") or {}
        if es.get("correlation_yaml"):
            jobs.append(_job("correlation", "{py} -m naturenet.models.time_series_analysis.correlation_analysis_shark "
                                            f"-y {q(abs_cfg(es['correlation_yaml']))}", cpus=ac))
        names = [j["name"] for j in jobs]
        last = [n for n in names if n in ("grid", "grid_year", "ppc_collect", "consistency_collect", "coupling_env",
                                          "geometry", "geometry_avl", "projection") or n.startswith("switch.")]
        last = list(dict.fromkeys(last))
        jobs.append(_job("synthesis", f"{py}synthesis -y {q(specs['synthesis'])}", after=_all(last, set(names))))

    if a.cpu_only:
        for j in jobs:
            j["gpu"] = 0
            j["env"] = dict(j.get("env") or {}, NATURENET_JAX_PLATFORM="cpu", JAX_PLATFORMS="cpu")
    L = st.d.get("launcher") or {}
    state = a.state_dir or L.get("state_dir") or os.path.join(st.out, "launch_state")
    env = {"PYTHONUNBUFFERED": "1", "JAX_COMPILATION_CACHE_DIR": os.path.join(state, "jax_cache"),
           "JAX_PERSISTENT_CACHE_MIN_COMPILE_TIME_SECS": "2"}
    if os.environ.get("REPTAXONOMY_SRC"):
        env["REPTAXONOMY_SRC"] = os.environ["REPTAXONOMY_SRC"]
    plan = dict(launcher=dict(state_dir=state, gpus=a.gpus, cpus=a.cpus, retries=int(L.get("retries", 1)), poll_sec=5,
                              env=env), vars=dict(py=a.python), jobs=jobs)
    return plan, specs


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-y", "--yaml", required=True, help="config/v2/drivers/<species>_drivers.yaml")
    ap.add_argument("--out", required=True, help="plan YAML to write")
    ap.add_argument("--only", default=",".join(GROUPS), help="comma list of " + ", ".join(GROUPS))
    ap.add_argument("--state_dir", default=None)
    ap.add_argument("--gpus", default="auto")
    ap.add_argument("--cpus", default="auto")
    ap.add_argument("--cpu_only", action="store_true")
    ap.add_argument("--python", default=shlex.quote(sys.executable))
    ap.add_argument("--specs_only", action="store_true", help="write the generated configs / specs, no plan")
    a = ap.parse_args(argv)
    st = Study(a.yaml)
    only = tuple(x.strip() for x in a.only.split(",") if x.strip())
    bad = [x for x in only if x not in GROUPS]
    if bad:
        ap.error(f"--only: unknown {bad}")
    if a.specs_only:
        print("specs:", write_specs(st, year_configs(st)))
        return
    plan, specs = build(st, a, only)
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w") as f:
        yaml.safe_dump(plan, f, sort_keys=False, width=140)
    n = sum(max(1, len(j.get("cases", []))) for j in plan["jobs"])
    print(f"wrote {a.out}: {len(plan['jobs'])} job groups, {n} jobs; specs in {os.path.dirname(specs['synthesis'])}")
    for j in plan["jobs"]:
        print(f"  {j['name']:56s} {max(1, len(j.get('cases', []))):5d}  cpus={j['cpus']} gpu={j['gpu']}")


if __name__ == "__main__":
    main()
